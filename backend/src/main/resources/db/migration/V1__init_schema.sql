-- 1. Tabela de Usuários
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

-- 2. Tabela de Regiões Monitoradas
CREATE TABLE regioes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    nivel_risco_atual VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX idx_regioes_ativo ON regioes(ativo);
CREATE INDEX idx_regioes_risco ON regioes(nivel_risco_atual);

-- 3. Tabela de Sensores
CREATE TABLE sensores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_id BIGINT NOT NULL,
    codigo_identificador VARCHAR(50) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    unidade_medida VARCHAR(10) NOT NULL,
    limite_atencao NUMERIC(10, 2) NOT NULL,
    limite_alerta NUMERIC(10, 2) NOT NULL,
    limite_perigo NUMERIC(10, 2) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    ultima_leitura TIMESTAMP WITHOUT TIME ZONE,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_sensor_codigo UNIQUE (codigo_identificador),
    CONSTRAINT fk_sensores_regiao FOREIGN KEY (regiao_id) REFERENCES regioes(id)
);

CREATE INDEX idx_sensores_regiao ON sensores(regiao_id);
CREATE INDEX idx_sensores_ativo ON sensores(ativo);
CREATE INDEX idx_sensores_codigo ON sensores(codigo_identificador);

-- 4. Tabela de Medições
CREATE TABLE medicoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id BIGINT NOT NULL,
    valor NUMERIC(10, 2) NOT NULL,
    data_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_medicoes_sensor FOREIGN KEY (sensor_id) REFERENCES sensores(id)
);

CREATE INDEX idx_medicoes_sensor_data ON medicoes(sensor_id, data_hora DESC);
CREATE INDEX idx_medicoes_data ON medicoes(data_hora DESC);

-- 5. Tabela de Alertas
CREATE TABLE alertas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_id BIGINT NOT NULL,
    sensor_id BIGINT NOT NULL,
    medicao_origem_id BIGINT NOT NULL,
    medicao_ultima_id BIGINT,
    nivel VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_emissao TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    data_ultima_ocorrencia TIMESTAMP WITHOUT TIME ZONE,
    data_resolucao TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_alertas_regiao FOREIGN KEY (regiao_id) REFERENCES regioes(id),
    CONSTRAINT fk_alertas_sensor FOREIGN KEY (sensor_id) REFERENCES sensores(id),
    CONSTRAINT fk_alertas_medicao_origem FOREIGN KEY (medicao_origem_id) REFERENCES medicoes(id),
    CONSTRAINT fk_alertas_medicao_ultima FOREIGN KEY (medicao_ultima_id) REFERENCES medicoes(id)
);

CREATE INDEX idx_alertas_regiao_ativo ON alertas(regiao_id, ativo);
CREATE INDEX idx_alertas_sensor_ativo ON alertas(sensor_id, ativo);
CREATE INDEX idx_alertas_status ON alertas(status);
CREATE INDEX idx_alertas_emissao ON alertas(data_emissao DESC);
